const router = require("express").Router();
const { requireIdentity } = require("../middleware/coldChainAccess");
const controller = require("../controllers/alertController");
router.use(requireIdentity);
router.get("/summary", controller.getAlertSummary);
router.get("/notifications", controller.getNotifications);
router.patch("/notifications/:notificationId/read", controller.markNotificationRead);
router.get("/policies/batch/:batchId", controller.getBatchTemperaturePolicy);
router.put("/policies/batch/:batchId", controller.setBatchTemperaturePolicy);
router.post("/policies/batch/:batchId/approve", controller.approveBatchPolicy);
router.post("/telemetry/check", controller.checkTelemetry);
router.get("/", controller.getAlerts);
router.get("/:alertId", controller.getAlertById);
router.patch("/:alertId/acknowledge", controller.acknowledgeAlert);
router.patch("/:alertId/quarantine", controller.quarantineAlert);
router.patch("/:alertId/review", controller.reviewAlert);
router.patch("/:alertId/clear", controller.clearAlert);
router.patch("/:alertId/resolve", controller.resolveAlert);
module.exports = router;
