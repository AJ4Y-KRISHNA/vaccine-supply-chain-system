function finiteNumber(value) {
  if (value === null || value === undefined || (typeof value === "string" && !value.trim())) {
    return null;
  }
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : null;
}

export function normalizeCoordinate(point) {
  if (!point || typeof point !== "object") return null;
  const latitude = finiteNumber(point.latitude ?? point.lat);
  const longitude = finiteNumber(point.longitude ?? point.lng);
  if (
    latitude === null ||
    longitude === null ||
    latitude < -90 ||
    latitude > 90 ||
    longitude < -180 ||
    longitude > 180
  ) {
    return null;
  }
  return { latitude, longitude };
}

export function normalizeRoutePoints(points) {
  if (!Array.isArray(points) || points.length < 2) return [];
  const normalized = points.map(normalizeCoordinate);
  return normalized.every(Boolean) ? normalized : [];
}

/**
 * Step 8 INIT routeInfo extension consumed by the panel:
 * routeCoordinates?: [{ latitude, longitude }, ...], or the explicit pair
 * originCoordinates/destinationCoordinates. Coordinates are never inferred
 * from city names or generated by the client.
 */
export function routePointsFromInit(routeInfo) {
  const fullRoute = normalizeRoutePoints(routeInfo?.routeCoordinates);
  if (fullRoute.length) return fullRoute;

  const origin = normalizeCoordinate(routeInfo?.originCoordinates);
  const destination = normalizeCoordinate(routeInfo?.destinationCoordinates);
  return origin && destination ? [origin, destination] : [];
}

export function distanceBetweenKm(from, to) {
  const first = normalizeCoordinate(from);
  const second = normalizeCoordinate(to);
  if (!first || !second) return null;

  const radians = (degrees) => (degrees * Math.PI) / 180;
  const latitudeDelta = radians(second.latitude - first.latitude);
  const longitudeDelta = radians(second.longitude - first.longitude);
  const haversine =
    Math.sin(latitudeDelta / 2) ** 2 +
    Math.cos(radians(first.latitude)) *
      Math.cos(radians(second.latitude)) *
      Math.sin(longitudeDelta / 2) ** 2;
  return 6371 * 2 * Math.atan2(Math.sqrt(haversine), Math.sqrt(1 - haversine));
}

export function routeDistanceKm(points) {
  const route = normalizeRoutePoints(points);
  if (!route.length) return null;
  return route.slice(1).reduce((distance, point, index) => {
    return distance + (distanceBetweenKm(route[index], point) || 0);
  }, 0);
}

export function simulatedSpeedKph(history) {
  if (!Array.isArray(history)) return null;
  const samples = history
    .map((reading) => ({
      coordinate: normalizeCoordinate({ latitude: reading?.gpsLat, longitude: reading?.gpsLng }),
      at: Date.parse(reading?.simulationClock || ""),
    }))
    .filter((sample) => sample.coordinate && Number.isFinite(sample.at));
  if (samples.length < 2) return null;

  const latest = samples[samples.length - 1];
  const previous = samples[samples.length - 2];
  const elapsedHours = (latest.at - previous.at) / 3_600_000;
  if (elapsedHours <= 0) return null;
  return distanceBetweenKm(previous.coordinate, latest.coordinate) / elapsedHours;
}

export function etaMinutes(totalDistance, progress, speedKph) {
  const distance = finiteNumber(totalDistance);
  const percent = finiteNumber(progress);
  const speed = finiteNumber(speedKph);
  if (distance === null || distance < 0 || percent === null || speed === null || speed <= 0) {
    return null;
  }
  return (Math.max(0, distance * (1 - Math.min(100, Math.max(0, percent)) / 100)) / speed) * 60;
}

export function formatEta(minutes) {
  if (!Number.isFinite(minutes) || minutes < 0) return "Unavailable";
  if (minutes === 0) return "Arrived";
  const rounded = Math.max(1, Math.round(minutes));
  const hours = Math.floor(rounded / 60);
  const remainingMinutes = rounded % 60;
  if (!hours) return `${remainingMinutes} min`;
  if (!remainingMinutes) return `${hours} hr`;
  return `${hours} hr ${remainingMinutes} min`;
}

export function formatCoordinate(point) {
  const coordinate = normalizeCoordinate(point);
  if (!coordinate) return "Unavailable";
  return `${coordinate.latitude.toFixed(5)}, ${coordinate.longitude.toFixed(5)}`;
}
